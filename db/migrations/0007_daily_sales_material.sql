-- ===========================================================================
--  0005 — 매출에 「재료비」 칸을 더한다
--
--  ★ 왜 (2026-09-14 · 매출 화면을 서버로 옮기다가 걸렸다)
--
--    `daily_sales` 는 매출·건수·메모만 받는다. 재료비 칸이 없다.
--    설계는 «재료비는 입고(`received_lines`)에서 합산한다» 고 봤기 때문이다.
--
--    그런데 **앱은 그렇게 안 쓴다.** 매출 화면이 재료비를 **사장님이 직접
--    적는 한 칸**으로 받는다 — "발주 금액을 그대로 적는 게 보통이다"
--    (`src/lib/sales.ts`). 품목별 입고를 매일 찍는 매장은 없기 때문이다.
--
--    칸이 없다고 그냥 안 옮기면, 화면은 "서버에 저장됐다" 고 말하면서
--    **재료비만 조용히 빠뜨린다.** 그러면 서버의 「남은 돈」이 실제보다 커진다.
--    반쪽으로 저장하느니 칸을 만든다.
--
--  ★ 나중에 입고를 제대로 찍게 되면 이 칸은 «사람이 적은 값» 으로 남고
--    합산값과 **대조하는 근거**가 된다. 지우지 않는다.
-- ===========================================================================

alter table public.daily_sales
  add column if not exists material_cost numeric(14,2);

comment on column public.daily_sales.material_cost is
  '사장님이 직접 적은 그날 재료비(원). 입고 합산이 아니라 사람이 적은 값이다';
