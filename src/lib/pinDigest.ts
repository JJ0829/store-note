/* ------------------------------------------------------------------ *
 * PIN을 저장소에 그대로 두지 않기 위한 단방향 요약값.
 *
 * ⚠ 암호학적으로 안전한 해시가 아니다. 브라우저 안에서 도는 이상
 *   안전할 수도 없다. 목적은 딱 하나 —
 *   **저장소를 눈으로 훑었을 때 PIN이 그대로 보이지 않게.**
 *
 * 원래 `ownerGate.ts` 안에 있던 것을 꺼냈다. 매장 PIN(`storeGate.ts`)이
 * 생기면서 같은 계산을 두 벌 두게 됐기 때문이다. 한 벌로 두면
 * 나중에 진짜 해시로 바꿀 때도 한 곳만 고치면 된다.
 *
 * **소금(salt)을 반드시 다르게 줄 것.** 사장님 PIN과 매장 PIN이
 * 우연히 같은 숫자여도 저장된 값은 달라야 한다. 같으면 한쪽 저장소를
 * 본 사람이 다른 쪽도 뚫린 걸 알게 된다.
 * ------------------------------------------------------------------ */

/** FNV-1a 계열. 36진수 문자열로 돌려준다 */
export function digest(salt: string, pin: string): string {
  let h = 2166136261;
  const salted = `${salt}:${pin}`;
  for (let i = 0; i < salted.length; i++) {
    h ^= salted.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(36);
}
